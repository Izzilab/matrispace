test_that("canonical coverage matches the apps", {
  canonical <- matrispace:::.get_ecm_genes()
  expect_length(canonical, 1027)
  expect_length(unique(matrisome_db$gene), 1029)
  expect_equal(anyDuplicated(matrisome_db$gene), 0L)
  expect_false(any(c("F8", "USH2A") %in% canonical))
  expect_setequal(unique(unlist(matrisome_signatures[1:6])), canonical)
  expect_false("F8" %in% matrispace:::.get_ecm_genes("ECM Regulators"))
  expect_false("USH2A" %in% matrispace:::.get_ecm_genes("ECM Glycoproteins"))
  expect_true("F8" %in% matrisome_signatures$hemostasis)
  expect_true("USH2A" %in% matrisome_signatures$basement_membrane)
  expect_true(all(c("F8", "USH2A") %in% matrisome_signatures$perivascular))
  expect_equal(nrow(matrisome_pairs), 16876L)
  expect_false(any(matrisome_pairs$Gene1 == matrisome_pairs$Gene2))
  expect_equal(anyDuplicated(paste(matrisome_pairs$Gene1, matrisome_pairs$Gene2)), 0L)
  expect_length(intersect(canonical, unique(c(matrisome_pairs$Gene1, matrisome_pairs$Gene2))), 929)
})
